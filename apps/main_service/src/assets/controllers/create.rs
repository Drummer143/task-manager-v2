use axum::{Extension, Json, extract::State, http::StatusCode};
use error_handlers::{ApiError, ErrorCode, FieldError, extract::ApiJson};
use serde::{Deserialize, Serialize};
use sql_models::asset::model::{Asset, AssetOwnerType, AssetStatus};
use utoipa::ToSchema;
use uuid::Uuid;

use crate::assets::{
    owner::Owner,
    repo::{AssetsRepository, NewAsset},
    upload_token::UploadTokenKey,
};

#[derive(Deserialize, ToSchema)]
pub struct AssetOwnerRequest {
    #[serde(rename = "type")]
    kind: AssetOwnerType,
    id: Uuid,
}

#[derive(Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct CreateAssetRequest {
    /// Generated by the client (UUIDv7). Sending the same request again returns a fresh token
    /// for the same asset, while it is still waiting for its file.
    id: Uuid,
    owner: AssetOwnerRequest,
    /// The file name, offered on download.
    name: String,
    /// In bytes.
    size: u64,
    /// blake3 of the content, lowercase hex; the uploaded file must match it.
    hash: String,
}

#[derive(Serialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct CreateAssetResponse {
    id: Uuid,
    /// Starts the upload in storage (`POST /actions/upload/init`). Valid for a day.
    upload_token: String,
}

/// Allows uploading a file for an owner (for now a workspace's icon). The asset waits for its
/// file; storage completes it once the upload is done. Unfinished ones are removed after a day.
#[utoipa::path(
    post,
    path = "/assets",
    operation_id = "createAsset",
    request_body = CreateAssetRequest,
    responses(
        (status = 201, description = "The upload is allowed", body = CreateAssetResponse),
        (status = 400, description = "Invalid request"),
        (status = 401, description = "Unauthorized"),
        (status = 404, description = "No such owner, or not one the user can see"),
        (status = 409, description = "An asset with this id already exists"),
        (status = 413, description = "The file is larger than the owner allows"),
        (status = 500, description = "Internal server error")
    ),
    tag = "Assets"
)]
pub async fn create_asset(
    State(pool): State<sqlx::PgPool>,
    State(tokens): State<UploadTokenKey>,
    Extension(user_id): Extension<Uuid>,
    ApiJson(body): ApiJson<CreateAssetRequest>,
) -> Result<(StatusCode, Json<CreateAssetResponse>), ApiError> {
    let owner = Owner {
        kind: body.owner.kind,
        id: body.owner.id,
    };
    let name = body.name.trim();
    validate(name, &body.hash)?;

    if body.size > owner.max_size() {
        return Err(ApiError::new(ErrorCode::FileTooLarge {
            max_bytes: owner.max_size(),
            actual_bytes: body.size,
        }));
    }

    owner.ensure_can_attach(&pool, user_id).await?;

    let created = AssetsRepository::create_pending(
        &pool,
        NewAsset {
            id: body.id,
            owner,
            name,
            // Not above the owner's limit, which fits
            size: body.size as i64,
            hash: &body.hash,
            visibility: owner.visibility(),
            created_by: user_id,
        },
    )
    .await?;

    let asset = match created {
        Some(asset) => asset,
        None => {
            let existing = AssetsRepository::get(&pool, body.id).await?;
            match existing {
                Some(asset) if is_retry(&asset, &body, user_id) => asset,
                _ => return Err(ApiError::new(ErrorCode::Conflict)),
            }
        }
    };

    let upload_token = tokens.issue(asset.id, user_id, &asset.name)?;

    Ok((
        StatusCode::CREATED,
        Json(CreateAssetResponse {
            id: asset.id,
            upload_token,
        }),
    ))
}

fn validate(name: &str, hash: &str) -> Result<(), ApiError> {
    let mut errors = Vec::new();

    if name.is_empty() {
        errors.push(FieldError::new("name", ErrorCode::Required));
    } else if name.chars().count() > 255 {
        errors.push(FieldError::new("name", ErrorCode::InvalidFormat));
    }

    let is_hash = hash.len() == 64 && hash.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'));
    if !is_hash {
        errors.push(FieldError::new("hash", ErrorCode::InvalidFormat));
    }

    if errors.is_empty() {
        Ok(())
    } else {
        Err(ApiError::validation(errors))
    }
}

/// The same request sent again (a lost response): same user, owner and file, still waiting.
fn is_retry(asset: &Asset, body: &CreateAssetRequest, user_id: Uuid) -> bool {
    asset.status == AssetStatus::Pending
        && asset.created_by == Some(user_id)
        && asset.owner_type == body.owner.kind
        && asset.owner_id == body.owner.id
        && asset.hash == body.hash
        && asset.size == body.size as i64
}

#[cfg(test)]
mod tests {
    use super::*;

    const HASH: &str = "af1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262";

    #[test]
    fn accepts_a_name_and_a_blake3_hash() {
        assert!(validate("icon.png", HASH).is_ok());
    }

    #[test]
    fn reports_every_bad_field_at_once() {
        let error = validate("", "AF13").unwrap_err();

        let fields: Vec<_> = error
            .to_body()
            .errors
            .into_iter()
            .map(|e| e.field)
            .collect();
        assert_eq!(fields, ["name", "hash"]);
    }

    #[test]
    fn refuses_an_uppercase_hash_and_a_long_name() {
        assert!(validate("icon.png", &HASH.to_uppercase()).is_err());
        assert!(validate(&"a".repeat(256), HASH).is_err());
        assert!(validate(&"я".repeat(255), HASH).is_ok());
    }
}
